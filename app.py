def validate_current_step(step: int) -> tuple[bool, str]:
    """단계 이동 전 필수 입력값 검증"""
    if step == 1:
        if not st.session_state.job_category or not st.session_state.job_title:
            return False, "희망 직무 대분류와 세부 직무를 선택해 주세요."
        if not st.session_state.skill:
            return False, "집중적으로 계획을 세워볼 핵심 역량 요소를 하나 선택해 주세요."

    elif step == 2:
        for qid in ["Q03", "Q04"]:
            if not st.session_state.answers.get(qid, "").strip():
                return False, f"{qid} ({CFG['questions'][qid]['label']}) 내용을 입력해 주세요."

    elif step == 3:
        for qid in ["Q05", "Q06", "Q07", "Q08"]:
            if not st.session_state.answers.get(qid, "").strip():
                return False, f"{qid} ({CFG['questions'][qid]['label']}) 내용을 입력해 주세요."

    elif step == 4:
        for qid in ["Q09", "Q10"]:
            if not st.session_state.answers.get(qid, "").strip():
                return False, f"{qid} ({CFG['questions'][qid]['label']}) 내용을 입력해 주세요."

    elif step == 5:
        if not st.session_state.answers.get("Q13", "").strip():
            return False, "Q13 (첫 행동) 내용을 입력해 주세요."

    elif step == 6:
        if not st.session_state.ind_skill:
            return False, "독립 수행 미션에서 연습할 다른 핵심 역량을 선택해 주세요."
        for field in CFG["assessment_fields"]:
            fid = field["id"]
            if not st.session_state.ind_answers.get(fid, "").strip():
                return False, f"독립 미션의 '{field['label']}' 항목을 작성해 주세요."

    return True, ""


def render_navigation(prev_label="← 이전 단계", next_label="다음 단계 →", show_prev=True, show_next=True):
    """하단 이전/다음 단계 이동 버튼 렌더링"""
    st.divider()
    col1, col2 = st.columns([1, 1])
    with col1:
        if show_prev and st.session_state.step > 0:
            if st.button(prev_label, use_container_width=True):
                st.session_state.step -= 1
                st.rerun()
    with col2:
        if show_next and st.session_state.step < 7:
            if st.button(next_label, type="primary", use_container_width=True):
                ok, err_msg = validate_current_step(st.session_state.step)
                if ok:
                    st.session_state.step += 1
                    st.rerun()
                else:
                    st.error(err_msg)


