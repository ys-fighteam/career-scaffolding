def build_ics_content(events: list) -> str:
    """캘린더 이벤트 리스트를 .ics 포맷 문자열로 변환"""
    nl = "\r\n"
    stamp = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")

    def safe_str(s: str) -> str:
        return (
            str(s)
            .replace("\\", "\\\\")
            .replace("\n", "\\n")
            .replace(",", "\\,")
            .replace(";", "\\;")
        )

    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//Pathfinder Career Scaffolding//KO",
        "CALSCALE:GREGORIAN",
    ]
    for ev in events:
        start_date_str = str(ev["date"]).replace("-", "")
        try:
            dt_obj = datetime.strptime(str(ev["date"]), "%Y-%m-%d").date()
            end_date_str = (dt_obj + timedelta(days=1)).strftime("%Y%m%d")
        except ValueError:
            end_date_str = start_date_str

        lines.extend(
            [
                "BEGIN:VEVENT",
                f"UID:{ev['id']}@pathfinder.local",
                f"DTSTAMP:{stamp}",
                f"DTSTART;VALUE=DATE:{start_date_str}",
                f"DTEND;VALUE=DATE:{end_date_str}",
                f"SUMMARY:{safe_str(ev['title'])}",
                f"DESCRIPTION:{safe_str(str(ev['minutes']) + '분 학습 활동 (' + st.session_state.skill + ')')}",
                "END:VEVENT",
            ]
        )
    lines.append("END:VCALENDAR")
    return nl.join(lines) + nl


